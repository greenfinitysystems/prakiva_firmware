Import("env")

from pathlib import Path

project_dir = Path(env.subst("$PROJECT_DIR"))
build_dir = Path(env.subst("$BUILD_DIR"))
spec_path = project_dir / "product_specs" / "aquarium_controller.json"
generated_include = build_dir / "generated_include"
generated_header = generated_include / "product" / "prakiva_product_specification.h"

if not spec_path.is_file():
    raise RuntimeError("Product Specification JSON not found: %s" % spec_path)

# Preserve the JSON file byte-for-byte inside the C++ string literal. The
# checksum therefore identifies the exact developer-maintained source file.
spec_text = spec_path.read_bytes().decode("utf-8")
delimiter = "PRKVSPEC"
if ")" + delimiter + '"' in spec_text:
    raise RuntimeError("Product Specification contains the reserved raw-string delimiter")

header_text = (
    "#pragma once\n\n"
    "// GENERATED by scripts/embed_product_spec.py. DO NOT EDIT.\n"
    "// Source: product_specs/aquarium_controller.json\n"
    "namespace prakiva\n{\n"
    "inline constexpr const char PRAKIVA_AQUARIUM_PRODUCT_SPEC[] = R\"" + delimiter + "("
    + spec_text + ")" + delimiter + "\";\n"
    "} // namespace prakiva\n"
)

generated_header.parent.mkdir(parents=True, exist_ok=True)
if not generated_header.exists() or generated_header.read_bytes() != header_text.encode("utf-8"):
    generated_header.write_bytes(header_text.encode("utf-8"))

env.Prepend(CPPPATH=[str(generated_include)])
print("[PRODUCT SPEC BUILD] Embedded %s (%u bytes)" % (spec_path.name, len(spec_text.encode("utf-8"))))
